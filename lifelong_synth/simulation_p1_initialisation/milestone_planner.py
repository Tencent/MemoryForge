"""
P1.5 Milestone Planner — Prior-Knowledge-Driven High-Res Detail Pre-planning
==============================================================================

Identifies key milestones for each life period and generates coarse-grained
skeletons that guide downstream P2 (event generation) and P3 (high-res
simulation).

Pipeline position: runs after P1c (Key Life Path Cache), before P2.

Two-step LLM flow:
  Step 1: Global milestone identification (1 LLM call covering all periods)
  Step 2: Skeleton generation per milestone (parallel LLM calls)

When no LLM client is provided (smoke-test mode), a deterministic rule-engine
fallback produces skeletons from the key_life_path_cache.
"""

from __future__ import annotations

import json
import logging
import os
from datetime import date
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field as PydanticField

logger = logging.getLogger(__name__)


# ═══════════════════════════════════════════════════════════════
# Data Models
# ═══════════════════════════════════════════════════════════════

class MilestoneHRSkeleton(BaseModel):
    """Pre-planned high-res event skeleton for a key milestone."""

    period_id: str = PydanticField(..., description="Parent period id, e.g. 'LP5'")
    milestone_type: str = PydanticField(
        ...,
        description="One of: stage_transition, achievement, decision, crisis",
    )
    milestone_name: str = PydanticField(
        ..., description="Short name, e.g. 'College Entrance Exam', 'PhD Defense'"
    )

    # Coarse-grained skeleton (generated by P1.5)
    summary_hint: str = PydanticField(
        ..., description="Event summary hint (100-200 chars, NOT the final summary)"
    )
    motivation_hint: str = PydanticField(
        default="", description="Trigger / motivation hint"
    )
    outcome_hint: str = PydanticField(
        default="", description="Expected outcome hint"
    )
    value_for_target: str = PydanticField(
        default="", description="Value for the protagonist"
    )

    # Temporal constraints
    expected_date_range: str = PydanticField(
        ..., description="Expected date range, e.g. '2016-06-07 to 2016-06-08'"
    )
    expected_duration_hours: float = PydanticField(
        default=4.0, description="Expected duration in hours"
    )

    # Narrative constraints (passed to Step 1b outline and P3 simulation)
    turning_point_hint: str = PydanticField(
        default="", description="Key turning point hint"
    )
    emotional_arc_hint: str = PydanticField(
        default="", description="Emotional arc hint"
    )
    mandatory_beats: List[str] = PydanticField(
        default_factory=list,
        description="Key beats that MUST be covered in P3 simulation",
    )

    # Coherence constraints (passed to Step 1a low-res generation)
    low_res_coherence_constraints: str = PydanticField(
        default="",
        description="Constraints for low-res events in the same period",
    )

    # Tier and priority
    simulation_tier: int = PydanticField(
        default=1,
        description="1=deep (full P3), 2=standard (short P3), 3=skeleton-only (no P3)",
    )
    priority_score: float = PydanticField(
        default=0.5, description="Priority score 0-1"
    )


class MilestoneIdentification(BaseModel):
    """LLM output for Step 1: identify one milestone per period."""

    period_id: str = PydanticField(..., description="Period id")
    milestone_name: str = PydanticField(..., description="Short milestone name")
    milestone_type: str = PydanticField(
        ..., description="stage_transition / achievement / decision / crisis"
    )
    expected_date_range: str = PydanticField(
        ..., description="Expected date range"
    )
    reason: str = PydanticField(..., description="Why this is the key milestone")
    priority_score: float = PydanticField(
        ..., description="Priority score 0-1"
    )


class MilestoneIdentificationOutput(BaseModel):
    """LLM output for Step 1: all milestones."""

    milestones: List[MilestoneIdentification] = PydanticField(
        ..., description="One milestone per period (skip periods with no clear milestone)"
    )


class SkeletonGenerationOutput(BaseModel):
    """LLM output for Step 2: skeleton for a single milestone."""

    summary_hint: str = PydanticField(
        ..., description="Event summary hint (100-200 chars)"
    )
    motivation_hint: str = PydanticField(default="", description="Trigger hint")
    outcome_hint: str = PydanticField(default="", description="Outcome hint")
    value_for_target: str = PydanticField(default="", description="Value for target")
    turning_point_hint: str = PydanticField(
        default="", description="Key turning point"
    )
    emotional_arc_hint: str = PydanticField(
        default="", description="Emotional arc"
    )
    mandatory_beats: List[str] = PydanticField(
        default_factory=list, description="Must-cover beats (2-4 items)"
    )
    low_res_coherence_constraints: str = PydanticField(
        default="", description="Coherence constraints for surrounding low-res events"
    )
    expected_duration_hours: float = PydanticField(
        default=4.0, description="Expected duration in hours"
    )


# ═══════════════════════════════════════════════════════════════
# Tier Assignment
# ═══════════════════════════════════════════════════════════════

def compute_simulation_tier(
    am_weight: float,
    priority_score: float,
) -> int:
    """Assign simulation tier based on AM weight and priority.

    Tier 1 (deep):          AM > 0.5 AND priority > 0.7
    Tier 2 (standard):      AM > 0.3 OR priority > 0.5
    Tier 3 (skeleton-only): everything else
    """
    if am_weight > 0.5 and priority_score > 0.7:
        return 1
    if am_weight > 0.3 or priority_score > 0.5:
        return 2
    return 3


def _estimate_am_weight_for_period(
    period: Dict[str, Any],
    birth_date_str: str,
    reference_date_str: str,
) -> float:
    """Estimate AM weight for a period using midpoint age."""
    try:
        birth = date.fromisoformat(birth_date_str)
        ref = date.fromisoformat(reference_date_str)
        dr = period.get("period_date_range", {})
        start = date.fromisoformat(dr.get("start_date", birth_date_str))
        end = date.fromisoformat(dr.get("end_date", reference_date_str))
        mid = start + (end - start) / 2
        years_ago = (ref - mid).days / 365.25
        current_age = (ref - birth).days / 365.25
        if current_age <= 0:
            return 0.0
        # Simplified AM weight: recency-based
        normalised = max(0.0, 1.0 - years_ago / current_age)
        return round(min(1.0, normalised), 3)
    except (ValueError, TypeError):
        return 0.3


# ═══════════════════════════════════════════════════════════════
# Rule-Engine Fallback (no LLM needed)
# ═══════════════════════════════════════════════════════════════

def _rule_engine_milestones(
    life_plan: Dict[str, Any],
    key_life_path_cache: Dict[str, Any],
    birth_date_str: str,
    reference_date_str: str,
) -> Dict[str, MilestoneHRSkeleton]:
    """Deterministic milestone extraction from key_life_path_cache.

    Looks for stage transitions, exams, and key events to pick the most
    important milestone per period.
    """
    periods = life_plan.get("life_periods", [])
    result: Dict[str, MilestoneHRSkeleton] = {}

    # Build year→period mapping
    year_to_period: Dict[int, str] = {}
    for p in periods:
        dr = p.get("period_date_range", {})
        try:
            s_year = int(dr.get("start_date", "")[:4])
            e_year = int(dr.get("end_date", "")[:4])
            for y in range(s_year, e_year + 1):
                year_to_period[y] = p["period_id"]
        except (ValueError, TypeError):
            pass

    # Collect candidate milestones from key_life_path_cache
    candidates: Dict[str, List[Dict[str, Any]]] = {}
    for year_str, year_data in key_life_path_cache.items():
        try:
            year = int(year_str)
        except (ValueError, TypeError):
            continue
        period_id = year_to_period.get(year)
        if not period_id:
            continue

        # Exams (high priority)
        exams = year_data.get("exams_this_year", [])
        if isinstance(exams, list):
            for exam in exams:
                name = exam.get("exam_name", "")
                if not name:
                    continue
                priority = 0.9 if name in ("高考", "中考", "Gaokao", "College Entrance Exam", "Zhongkao") else 0.6
                candidates.setdefault(period_id, []).append({
                    "name": name,
                    "type": "stage_transition" if name in ("高考", "中考", "Gaokao", "College Entrance Exam", "Zhongkao") else "achievement",
                    "date_range": exam.get("date_range", f"{year}-06"),
                    "description": exam.get("description", name),
                    "priority": priority,
                    "year": year,
                })

        # Key events (stage transitions)
        events = year_data.get("key_events", [])
        if isinstance(events, list):
            for evt in events:
                name = evt.get("event_name", "")
                is_transition = evt.get("is_stage_transition", False)
                if not name:
                    continue
                # Graduation events are important milestones
                if "毕业" in name or "graduation" in name.lower():
                    priority = 0.7
                elif is_transition:
                    priority = 0.5
                else:
                    priority = 0.3
                candidates.setdefault(period_id, []).append({
                    "name": name,
                    "type": "stage_transition" if is_transition else "achievement",
                    "date_range": evt.get("date", f"{year}-06"),
                    "description": evt.get("description", name),
                    "priority": priority,
                    "year": year,
                })

    # Also check likely_transition_triggers from life_plan periods
    period_lookup = {p["period_id"]: p for p in periods}
    for period_id, p in period_lookup.items():
        triggers = p.get("likely_transition_triggers", [])
        for trigger in triggers:
            trigger_lower = trigger.lower()
            # Boost priority for well-known milestones mentioned in triggers
            if any(kw in trigger_lower for kw in ["高考", "答辩", "毕业", "入职", "面试", "gaokao", "defense", "graduation", "onboarding", "interview"]):
                for cand in candidates.get(period_id, []):
                    if any(kw in cand["name"] for kw in ["高考", "答辩", "毕业", "gaokao", "defense", "graduation"]):
                        cand["priority"] = min(1.0, cand["priority"] + 0.1)

    # Select best candidate per period
    for period_id, cands in candidates.items():
        if not cands:
            continue
        best = max(cands, key=lambda c: c["priority"])

        am_weight = _estimate_am_weight_for_period(
            period_lookup.get(period_id, {}),
            birth_date_str,
            reference_date_str,
        )
        tier = compute_simulation_tier(am_weight, best["priority"])

        result[period_id] = MilestoneHRSkeleton(
            period_id=period_id,
            milestone_type=best["type"],
            milestone_name=best["name"],
            summary_hint=best["description"],
            motivation_hint="",
            outcome_hint="",
            value_for_target="",
            expected_date_range=best["date_range"],
            expected_duration_hours=4.0,
            turning_point_hint="",
            emotional_arc_hint="",
            mandatory_beats=[],
            low_res_coherence_constraints="",
            simulation_tier=tier,
            priority_score=best["priority"],
        )

    return result


