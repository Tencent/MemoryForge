class EducationStage(BaseModel):
    """A single stage in the education system of the inferred social context."""
    stage_name: str = Field(..., description="Education stage identifier, e.g. 'primary_school', 'undergraduate', 'doctoral'")
    typical_entry_age: int = Field(..., description="Typical age at which students enter this stage")
    typical_duration_years: int = Field(..., description="Typical duration in years")
    is_mandatory: bool = Field(False, description="Whether this stage is part of compulsory education")
    entry_month: int = Field(
    0,
    description=(
        "Month when the academic year starts (1-12). "
        "MUST be inferred from the country's education system: "
        "9 for Northern Hemisphere (China/UK/USA), 2 for Southern Hemisphere (NZ/Australia), "
        "4 for Japan, 3 for Korea, etc. "
        "0 means not yet set and MUST be overridden."
    )
)
    notes: str = Field("", description="Additional notes, e.g. 'K-12 system', '6-year medical program'")


class CareerPathNorm(BaseModel):
    """Typical career entry norms for the target occupation in the inferred social context."""
    typical_entry_age_min: int = Field(..., description="Minimum typical age for entering this career")
    typical_entry_age_max: int = Field(..., description="Maximum typical age for entering this career")
    typical_prerequisites: List[str] = Field(default_factory=list, description="Typical prerequisites, e.g. ['bachelor degree', 'PhD']")
    notes: str = Field("", description="Additional notes about career path norms")


class SocialInstitution(BaseModel):
    """A social institution that may affect life stage planning (e.g. military service, retirement)."""
    institution_name: str = Field(..., description="Institution identifier, e.g. 'military_service', 'retirement'")
    applies_to: str = Field(..., description="Who this applies to, e.g. 'all_males', 'all_citizens'")
    typical_age_min: int = Field(..., description="Minimum typical age for this institution")
    typical_age_max: int = Field(..., description="Maximum typical age for this institution")
    typical_duration_months: int = Field(0, description="Typical duration in months (0 if not applicable)")
    is_mandatory: bool = Field(False, description="Whether this is mandatory")
    notes: str = Field("", description="Additional notes")


class PersonaSpecificAdjustment(BaseModel):
    """An adjustment to the typical social context rules based on persona_brief_text."""
    adjustment_type: str = Field(..., description="Type of adjustment, e.g. 'direct_phd_admission', 'child_prodigy', 'gap_year'")
    description: str = Field(..., description="Description of the adjustment")
    affected_stages: List[str] = Field(default_factory=list, description="Which education/career stages are affected")
    rationale: str = Field("", description="Why this adjustment is needed based on persona_brief_text")


class SocialContextProfile(BaseModel):
    """
    Complete social context profile inferred from persona characteristics.
    Used as constraints for life period planning, transition date inference, and plan review.
    """
    country: str = Field(..., description="Country or region code")
    birth_era: str = Field(..., description="Birth era descriptor, e.g. '1990s', '2000s'")
    education_system: List[EducationStage] = Field(..., description="Ordered list of education stages from earliest to latest")
    career_path_norms: CareerPathNorm = Field(..., description="Career entry norms for the target occupation")
    social_institutions: List[SocialInstitution] = Field(default_factory=list, description="Relevant social institutions (military service, retirement, etc.)")
    persona_specific_adjustments: List[PersonaSpecificAdjustment] = Field(default_factory=list, description="Adjustments based on persona_brief_text")
    confidence: Literal["high", "medium", "low"] = Field("medium", description="Overall confidence in the inferred social context")
    summary: str = Field("", description="One-line summary of the social context")


