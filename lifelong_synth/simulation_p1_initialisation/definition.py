class PathwayDimension(BaseModel):
    """A single dimension of the inferred life pathway."""
    dimension: str = Field(
        ...,
        description="The life dimension, e.g., 'education', 'career', "
                    "'social_institution', 'family'"
    )
    pathway_type: str = Field(
        ...,
        description="The inferred pathway type for this dimension, "
                    "e.g., 'direct_phd', 'standard_linear', 'career_switch', "
                    "'military_exempt', 'standard_family'"
    )
    key_stages: List[str] = Field(
        default_factory=list,
        description="Ordered list of key stages/milestones in this dimension, "
                    "e.g., ['primary_school(6y)', 'junior_secondary(3y)', "
                    "'senior_secondary(3y)', 'undergraduate(4y)', 'doctoral(5y)']"
    )
    deviations_from_typical: List[str] = Field(
        default_factory=list,
        description="How this pathway differs from the typical one. "
                    "Use deviation type prefix: SKIP/INSERT/EXTEND/SHORTEN/"
                    "REORDER/PARALLEL/SPLIT/INTERRUPT_RESUME/MERGE. "
                    "e.g., 'SKIP: No independent master stage (direct PhD)'"
    )
    confidence: Literal["high", "medium", "low"] = Field(
        "medium",
        description="Confidence in this inference. 'low' means insufficient "
                    "signals — defaulting to typical pathway"
    )
    inference_basis: str = Field(
        "",
        description="What persona_brief_text signals led to this inference, "
                    "including both explicit mentions and notable absences"
    )


class SuggestedPeriod(BaseModel):
    """A single suggested life period in the period plan.

    Used by InferredPersonaPathway.suggested_periods to guide backward generation.
    Covers all persona types: students, career professionals, retirees, etc.
    """
    stage_key: str = Field(
        ...,
        description=(
            "Stage identifier matching the education system stage_name or a custom label. "
            "e.g. 'early_childhood', 'primary_school', 'secondary_school_lower', "
            "'undergraduate', 'early_career', 'mid_career', 'gap_transition', 'retirement'"
        )
    )
    label_hint: str = Field(
        ...,
        description=(
            "Human-readable label hint for this period. "
            "For education stages, include position info: "
            "e.g. 'Primary school Years 1-3 (foundation)', "
            "'Primary school Years 4-6 (consolidation)', "
            "'Secondary school Years 9-11 (NCEA lower)', "
            "'Undergraduate Year 1-2 (exploration)', "
            "'Undergraduate Year 3-4 (specialization)'. "
            "For non-education stages: 'Early career entry (years 1-3)', "
            "'Mid-career leadership phase', 'Active retirement (years 1-5)', etc."
        )
    )
    approx_start: str = Field(
        ...,
        description=(
            "Approximate start date YYYY-MM (year-month only, not day). "
            "Derived from SocialContextProfile education timeline anchors "
            "(birth_date + typical_entry_age + duration)."
        )
    )
    approx_end: str = Field(
        ...,
        description="Approximate end date YYYY-MM (year-month only, not day)"
    )
    stage_position_hint: Optional[str] = Field(
        None,
        description=(
            "A hint describing where this period falls within its parent stage. "
            "For education stages: grade range, e.g. 'Year 4-6 of 6', 'Year 1-2 of 4'. "
            "For career stages: phase description, e.g. 'early career (years 1-3)', "
            "'mid-career leadership phase', 'pre-retirement wind-down'. "
            "For family stages: 'young children phase', 'empty nest phase'. "
            "For retirement: 'active retirement', 'late retirement'. "
            "None if the stage is short (<2 years) or has no meaningful sub-phases."
        )
    )
    consolidation_rationale: str = Field(
        "",
        description=(
            "Why these years/months are grouped into one period rather than split further. "
            "e.g. 'Years 1-3 share the same developmental theme (foundation building) "
            "with no significant qualitative shift', "
            "'Single year due to major transition event (NCEA Level 3 + university application)', "
            "'Career years 1-5 grouped as early exploration before first promotion'"
        )
    )


class InferredPersonaPathway(BaseModel):
    """
    The actual life pathway inferred for this specific persona.
    Output of Step 0b. PRIMARY reference for Plan Generation.
    """
    dimensions: List[PathwayDimension] = Field(
        ...,
        description="One entry per life dimension (education, career, etc.)"
    )
    overall_rationale: str = Field(
        ...,
        description="Overall rationale for the inferred pathway"
    )
    persona_brief_signals: List[str] = Field(
        default_factory=list,
        description="Key signals from persona_brief_text: "
                    "prefix with EXPLICIT/ABSENT/INFERRED"
    )
    suggested_periods: List[SuggestedPeriod] = Field(
        default_factory=list,
        description=(
            "Ordered list of suggested life periods, from EARLIEST to LATEST. "
            "This is the PRIMARY reference for backward generation — "
            "the backward loop MUST generate exactly these periods (one per entry). "
            "Each entry specifies the stage, approximate dates, position hint, "
            "and why years are grouped this way. "
            "Generated by combining SocialContextProfile rules with persona_brief_text signals. "
            "MUST cover the full life span from birth to reference_date with no gaps."
        )
    )


