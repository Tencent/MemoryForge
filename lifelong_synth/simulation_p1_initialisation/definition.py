"""
P1 Initialisation — Data Model Definitions
============================================
Centralised data model definitions for the P1 Initialisation module.

This file contains all Pydantic data models used by the
DevelopmentAwareLifePeriodPlanner, ParticipantPoolManager, and related
components, including:

  Life-Period Planner models:
  - GlobalSummary: top-level plan metadata
  - PeriodDateRange: date range for a life period
  - LifePeriod: a single life period with all attributes
  - MilestonePlan: the complete life period plan
  - PlanValidationReport: validation results for a plan
  - TransitionDateHint: a single inferred transition date
  - InferredTemporalConstraints: normalised temporal constraints
  - TransitionDateHints: collection of transition date hints

  Participant Pool models:
  - DateOfBirth: structured date-of-birth
  - LocationInfo: geographic location
  - SelfSystemAnchor: value anchor
  - InteractionRecord: a single interaction record
  - Participant: full participant profile
  - Phase1BasicInfo: Phase-1 LLM output (basic identity)
  - Phase1ParticipantList: Phase-1 LLM output (participant list)
  - Phase2TemporalBriefs: Phase-2 LLM output (temporal briefs)
  - Phase3FullProfile: Phase-3 LLM output (extended profile)
  - Phase4SingleMemory: Phase-4 LLM output (single memory)
  - Phase4InitialMemories: Phase-4 LLM output (initial memories)
  - Phase5ConsistencyResult: Phase-5 LLM output (consistency check)
"""

from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field, field_validator


# ==========================================
# Life-Period Planner Data Structures
# ==========================================

class GlobalSummary(BaseModel):
    target_age_exact: int = Field(..., description="Final age of the target person")
    total_periods: int = Field(..., description="Total number of life stages")
    planning_logic: str = Field(..., description="One-sentence summary of the underlying logic of the overall life plan (e.g., from an early family environment emphasizing learning to career convergence in frontier AI)")

class PeriodDateRange(BaseModel):
    start_date: str = Field(..., description="Stage start date, ISO format YYYY-MM-DD")
    end_date: str = Field(..., description="Stage end date, ISO format YYYY-MM-DD")

class LifePeriod(BaseModel):
    period_id: str = Field(..., description="Stage ID, e.g. 'LP1', 'LP2'")
    stage_label: str = Field(..., description="A semantic stage label auto-generated by the model (snake_case format), summarizing the core nature of this stage. E.g., 'early_childhood', 'undergraduate_exploration', 'phd_research_pivot', 'career_entry_adaptation'. For life gap/transition periods, must use 'gap_transition'. Labels should reflect the actual content of the stage, not apply fixed developmental psychology categories.")
    title: str = Field(..., description="A life summary title for this stage")
    dominant_theme: str = Field(..., description="The core organizing logic and dominant theme of this stage")
    developmental_tasks: List[str] = Field(..., description="Developmental tasks that need to be accomplished in this stage")
    stage_goals: List[str] = Field(..., description="What goals the working self tends to organize around in this stage")
    salient_pressures: List[str] = Field(..., description="Typical pressures faced in this stage")
    salient_opportunities: List[str] = Field(..., description="Opportunity windows that converge toward the target persona")
    likely_transition_triggers: List[str] = Field(..., description="Events most likely to push this stage into the next stage")
    period_date_range: PeriodDateRange = Field(..., description="The precise date closed interval for this stage (year-month-day, inclusive)")

    # ── Stage type tags (generated by P1 LLM, consumed by TC Engine) ──
    is_education_stage: bool = Field(
        False,
        description=(
            "Whether this period involves education/learning activities "
            "(kindergarten, school, university, graduate, doctoral, etc.). "
            "A period can be both education and work (e.g., PhD with research work)."
        )
    )
    is_work_stage: bool = Field(
        False,
        description=(
            "Whether this period involves work/career activities "
            "(internship, full-time job, research work, entrepreneurship, etc.). "
            "PhD periods with research work should be marked as both education and work."
        )
    )
    is_transition_stage: bool = Field(
        False,
        description=(
            "Whether this period is a transition/gap period "
            "(waiting for enrollment, gap between graduation and employment, career change buffer, etc.). "
            "Periods with stage_label 'gap_transition' must be marked True."
        )
    )

class MilestonePlan(BaseModel):
    global_summary: GlobalSummary
    life_periods: List[LifePeriod] = Field(..., description="List of life stages sorted by `period_date_range.start_date` ascending")

class PlanReviewIssue(BaseModel):
    issue_id: str = Field(..., description="Unique issue identifier")
    severity: Literal["low", "medium", "high", "critical"] = Field(..., description="Issue severity")
    issue_type: str = Field(..., description="General reasonableness issue type")
    affected_period_ids: List[str] = Field(default_factory=list, description="Impacted life periods")
    reason: str = Field(..., description="Why this issue is problematic")
    evidence: List[str] = Field(default_factory=list, description="Concrete supporting evidence")


class PeriodContentRefresh(BaseModel):
    """LLM output: refreshed content fields for a single period after stage_label/title patch."""
    dominant_theme: str = Field(..., description="The core organizing logic and dominant theme of this stage (must be semantically consistent with the new stage_label and title)")
    developmental_tasks: List[str] = Field(..., description="Developmental tasks that need to be accomplished in this stage (3-5 items)")
    stage_goals: List[str] = Field(..., description="What goals the working self tends to organize around in this stage (3-5 items)")
    salient_pressures: List[str] = Field(..., description="Typical pressures faced in this stage (2-4 items)")
    salient_opportunities: List[str] = Field(..., description="Opportunity windows that converge toward the target persona (2-4 items)")
    likely_transition_triggers: List[str] = Field(..., description="Events most likely to push this stage into the next stage (1-3 items)")

    # ── Stage type tags (synced when stage_label/title changes) ──
    is_education_stage: bool = Field(False, description="Re-evaluate based on refreshed stage_label and title")
    is_work_stage: bool = Field(False, description="Re-evaluate based on refreshed stage_label and title")
    is_transition_stage: bool = Field(False, description="Re-evaluate based on refreshed stage_label and title")


class PlanPatchAction(BaseModel):
    patch_type: Literal[
        "update_start_date",
        "update_end_date",
        "update_title",
        "update_stage_label",
        "update_transition_anchor",
        "update_is_education_stage",
        "update_is_work_stage",
        "update_is_transition_stage",
        "update_dominant_theme",
        "update_developmental_tasks",
        "update_stage_goals",
        "update_salient_pressures",
        "update_salient_opportunities",
        "update_likely_transition_triggers",
    ] = Field(..., description="Supported local patch type")
    period_id: str = Field(..., description="Target period id")
    field_path: str = Field(..., description="Target field path within the plan")
    new_value: Any = Field(..., description="Replacement value")
    rationale: str = Field(..., description="Why this local patch should fix the issue")


class PlanReviewReport(BaseModel):
    status: Literal["pass", "needs_patch", "needs_regeneration"] = Field(..., description="Review verdict")
    issues: List[PlanReviewIssue] = Field(default_factory=list, description="Detected issues")
    patches: List[PlanPatchAction] = Field(default_factory=list, description="Suggested local patches")
    review_summary: str = Field("", description="High-level review summary")


class PeriodJudgement(BaseModel):
    """Structured verdict for a single period from the Judge stage."""
    period_id: str = Field(..., description="Target period id")
    verdict: Literal["pass", "rewrite", "split", "merge", "delete"] = Field(
        ...,
        description=(
            "pass: period is correct. "
            "rewrite: content needs regeneration (dates unchanged). "
            "split: period spans qualitatively different phases and should be split. "
            "merge: period should be merged with an adjacent period (too short / semantically redundant). "
            "delete: period should not exist (contradicts persona pathway SKIP, or is redundant)."
        ),
    )
    reason: str = Field(..., description="Why this verdict was chosen")
    instruction: str = Field(
        "",
        description=(
            "Specific action instruction. "
            "rewrite: what to change (e.g. 'stage_label should be X, title should reflect Y'). "
            "split: 'split at YYYY-MM-DD into phase A and phase B because ...'. "
            "merge: 'merge with LP2 because both are semantically redundant pre-school periods'. "
            "delete: 'this period contradicts SKIP marker in persona pathway'. "
            "pass: empty."
        ),
    )
    split_point: Optional[str] = Field(
        None,
        description="Only used when verdict=split. The split-point date in ISO format (YYYY-MM-DD).",
    )
    merge_with_prev: bool = Field(
        True,
        description=(
            "Only used when verdict=merge. "
            "True = merge with the previous period (default). "
            "False = merge with the next period."
        ),
    )
    coherence_with_next: str = Field(
        "",
        description="Assessment of coherence between this period and the next already-reviewed period.",
    )


class PlanJudgementReport(BaseModel):
    """Complete output of the Judge stage — one judgement per period."""
    judgements: List[PeriodJudgement] = Field(
        ...,
        description="One PeriodJudgement per period, ordered from last period to first (reverse).",
    )
    global_assessment: str = Field(
        "",
        description="High-level assessment of the entire plan's structural quality.",
    )


class PlanDurationIssue(BaseModel):
    """A single duration-related issue identified by LLM-based validation."""
    period_id: str = Field(..., description="The period_id with the issue")
    issue_type: Literal[
        "too_short_for_content",
        "too_short_for_education_stage",
        "extreme_adjacent_imbalance",
        "statistical_outlier",
        "other",
    ] = Field(..., description="Type of duration issue")
    severity: Literal["low", "medium", "high"] = Field(..., description="Issue severity")
    description: str = Field(..., description="Human-readable description of the issue")
    suggestion: str = Field("", description="Suggested fix direction")


class PlanDurationValidationReport(BaseModel):
    """LLM output: duration reasonableness validation for the entire plan."""
    is_valid: bool = Field(
        ...,
        description=(
            "True if all period durations are reasonable given the persona's "
            "social context, education system, and life trajectory. "
            "False if any period has a problematic duration."
        ),
    )
    issues: List[PlanDurationIssue] = Field(
        default_factory=list,
        description="List of duration issues found. Empty if is_valid=True.",
    )
    summary: str = Field(
        "",
        description="One-line summary of the duration validation result.",
    )


# ==========================================
# CBQA (Causal Backpropagation QA) Data Structures
# ==========================================

class CausalAttribution(BaseModel):
    """Attribution of one validation failure to an upstream pipeline stage."""
    failure_id: str = Field(..., description="Identifier for the validation failure, e.g. 'LP7_too_short'")
    failure_description: str = Field(..., description="Description of the validation failure")
    attributed_stage_id: str = Field(
        ...,
        description=(
            "The pipeline stage that is the root cause. "
            "One of: 'step_0a' (Social Context), 'step_0b' (Persona Pathway), "
            "'step_4' (Transition Hints), 'step_7' (Plan Generation)"
        ),
    )
    attribution_reasoning: str = Field(..., description="Why this stage is identified as the root cause")
    correction_signal: str = Field(
        ...,
        description=(
            "Specific correction instruction for the attributed stage. "
            "Must be concrete, e.g. 'undergrad_graduation should be 2020-06-30 "
            "(1998+22=2020), not 2019-06-30'"
        ),
    )
    confidence: Literal["high", "medium", "low"] = Field("medium", description="Confidence in this attribution")


class ErrorAttributionReport(BaseModel):
    """Output of the CBQA Error Attribution Agent."""
    attributions: List[CausalAttribution] = Field(
        ..., description="List of causal attributions, one per validation failure"
    )
    summary: str = Field("", description="One-line summary of the attribution analysis")
    recommended_re_execution_stages: List[str] = Field(
        default_factory=list,
        description=(
            "Ordered list of pipeline stage IDs that should be re-executed. "
            "e.g. ['step_4', 'step_7'] means re-run Transition Hints then Plan Generation"
        ),
    )


class PlanValidationReport(BaseModel):
    is_valid: bool = Field(..., description="Whether the plan passes general consistency checks")
    risk_level: Literal["low", "medium", "high"] = Field(..., description="Risk level")
    key_issues: List[str] = Field(default_factory=list, description="Key issues identified")
    recommendations: List[str] = Field(default_factory=list, description="Suggested fix directions")

class TransitionDateHint(BaseModel):
    transition_key: str = Field(..., description="Transition point identifier, e.g. phd_graduation / first_job_entry")
    transition_label: str = Field(..., description="Human-readable name for the transition point")
    anchor_date: str = Field(..., description="Transition anchor date, ISO format YYYY-MM-DD")
    confidence: Literal["low", "medium", "high"] = Field(..., description="Confidence level of this date inference")
    is_hard_constraint: bool = Field(False, description="Whether this should be treated as a hard constraint for stage boundaries")
    rationale: str = Field(..., description="Which clues from the input this date was derived from")

class InferredTemporalConstraints(BaseModel):
    current_role_start_date: Optional[str] = Field(None, description="Current role start date (YYYY-MM-DD), can be empty if not reliably inferred")
    pre_current_transition_anchor_date: Optional[str] = Field(None, description="Key transition anchor date before the current role (YYYY-MM-DD), e.g. graduation or key turning point")
    transition_semantic_hint: Literal["general", "graduation"] = Field("general", description="Transition anchor semantic hint")
    rationale: str = Field("", description="Basis for this constraint inference")

class TransitionDateHints(BaseModel):
    summary: str = Field("", description="One-sentence summary of the key transition date set")
    transition_dates: List[TransitionDateHint] = Field(default_factory=list, description="Key transition dates that need special attention in the simulation")
    inferred_temporal_constraints: InferredTemporalConstraints = Field(default_factory=InferredTemporalConstraints, description="Temporal constraints normalized from transition dates by the first LLM step")


